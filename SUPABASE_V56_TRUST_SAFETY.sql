-- 1) حقول الثقة والتوثيق في الملفات الشخصية
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS is_verified boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS verified_at timestamptz,
  ADD COLUMN IF NOT EXISTS verified_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS trust_score integer NOT NULL DEFAULT 0;

ALTER TABLE public.profiles
  DROP CONSTRAINT IF EXISTS profiles_trust_score_check;
ALTER TABLE public.profiles
  ADD CONSTRAINT profiles_trust_score_check CHECK (trust_score >= 0 AND trust_score <= 100);

-- 2) حظر المستخدمين
CREATE TABLE IF NOT EXISTS public.user_blocks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  blocker_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  blocked_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(blocker_id, blocked_id),
  CHECK(blocker_id <> blocked_id)
);
ALTER TABLE public.user_blocks ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS user_blocks_select_own ON public.user_blocks;
CREATE POLICY user_blocks_select_own ON public.user_blocks FOR SELECT TO authenticated
USING (blocker_id = auth.uid());
DROP POLICY IF EXISTS user_blocks_insert_own ON public.user_blocks;
CREATE POLICY user_blocks_insert_own ON public.user_blocks FOR INSERT TO authenticated
WITH CHECK (blocker_id = auth.uid() AND blocked_id <> auth.uid());
DROP POLICY IF EXISTS user_blocks_delete_own ON public.user_blocks;
CREATE POLICY user_blocks_delete_own ON public.user_blocks FOR DELETE TO authenticated
USING (blocker_id = auth.uid());
CREATE INDEX IF NOT EXISTS user_blocks_blocker_idx ON public.user_blocks(blocker_id, created_at DESC);
CREATE INDEX IF NOT EXISTS user_blocks_blocked_idx ON public.user_blocks(blocked_id);

-- 3) سجل التدقيق الإداري
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id uuid,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS audit_logs_admin_read ON public.audit_logs;
CREATE POLICY audit_logs_admin_read ON public.audit_logs FOR SELECT TO authenticated
USING (public.has_permission('manage_users'));
CREATE INDEX IF NOT EXISTS audit_logs_created_idx ON public.audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_entity_idx ON public.audit_logs(entity_type, entity_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.write_audit_log(
  p_action text,
  p_entity_type text,
  p_entity_id uuid DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb
) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  INSERT INTO public.audit_logs(actor_id, action, entity_type, entity_id, metadata)
  VALUES(auth.uid(), left(p_action,100), left(p_entity_type,50), p_entity_id, coalesce(p_metadata,'{}'::jsonb));
END; $$;
REVOKE ALL ON FUNCTION public.write_audit_log(text,text,uuid,jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.write_audit_log(text,text,uuid,jsonb) TO authenticated;

-- 4) توثيق الحسابات عبر صلاحية إدارية
CREATE OR REPLACE FUNCTION public.admin_set_user_verification(
  target_user_id uuid,
  new_verified boolean
) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_uid uuid := auth.uid();
BEGIN
  IF NOT public.has_permission('manage_users') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id=target_user_id) THEN RAISE EXCEPTION 'المستخدم غير موجود'; END IF;
  UPDATE public.profiles
  SET is_verified=new_verified,
      verified_at=CASE WHEN new_verified THEN now() ELSE NULL END,
      verified_by=CASE WHEN new_verified THEN v_uid ELSE NULL END,
      updated_at=now()
  WHERE id=target_user_id;
  PERFORM public.write_audit_log('user_verification_changed','profile',target_user_id,jsonb_build_object('verified',new_verified));
  RETURN FOUND;
END; $$;
GRANT EXECUTE ON FUNCTION public.admin_set_user_verification(uuid,boolean) TO authenticated;

-- 5) حظر/فك حظر مستخدم بواسطة RPC لتسجيل العملية
CREATE OR REPLACE FUNCTION public.block_user(p_blocked_id uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR p_blocked_id IS NULL OR p_blocked_id = auth.uid() THEN RAISE EXCEPTION 'مستخدم غير صالح'; END IF;
  INSERT INTO public.user_blocks(blocker_id,blocked_id) VALUES(auth.uid(),p_blocked_id)
  ON CONFLICT(blocker_id,blocked_id) DO NOTHING;
  RETURN true;
END; $$;
GRANT EXECUTE ON FUNCTION public.block_user(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.unblock_user(p_blocked_id uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  DELETE FROM public.user_blocks WHERE blocker_id=auth.uid() AND blocked_id=p_blocked_id;
  RETURN FOUND;
END; $$;
GRANT EXECUTE ON FUNCTION public.unblock_user(uuid) TO authenticated;

-- 6) منع التفاعل المباشر مع مستخدم محظور عند إنشاء محادثة
CREATE OR REPLACE FUNCTION public.can_message_user(p_other_user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT auth.uid() IS NOT NULL
     AND p_other_user_id IS NOT NULL
     AND auth.uid() <> p_other_user_id
     AND NOT EXISTS (
       SELECT 1 FROM public.user_blocks b
       WHERE (b.blocker_id=auth.uid() AND b.blocked_id=p_other_user_id)
          OR (b.blocker_id=p_other_user_id AND b.blocked_id=auth.uid())
     );
$$;
GRANT EXECUTE ON FUNCTION public.can_message_user(uuid) TO authenticated;

-- 7) تحسين البلاغات: فهرسة + RPC للمراجعة
ALTER TABLE public.ad_reports
