CREATE INDEX IF NOT EXISTS ad_reports_status_created_idx ON public.ad_reports(status, created_at DESC);

CREATE OR REPLACE FUNCTION public.moderate_ad_report(
  p_report_id uuid,
  p_status text,
  p_admin_note text DEFAULT NULL
) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_ad_id uuid;
BEGIN
  IF NOT public.has_permission('manage_reports') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF p_status NOT IN ('reviewed','dismissed') THEN RAISE EXCEPTION 'حالة غير صالحة'; END IF;
  SELECT ad_id INTO v_ad_id FROM public.ad_reports WHERE id=p_report_id FOR UPDATE;
  IF v_ad_id IS NULL THEN RAISE EXCEPTION 'البلاغ غير موجود'; END IF;
  UPDATE public.ad_reports
  SET status=p_status,
      admin_note=NULLIF(left(coalesce(p_admin_note,''),2000),''),
      reviewed_by=auth.uid(),
      resolved_at=now()
  WHERE id=p_report_id;
  PERFORM public.write_audit_log('ad_report_moderated','ad_report',p_report_id,jsonb_build_object('status',p_status,'ad_id',v_ad_id));
  RETURN true;
END; $$;
GRANT EXECUTE ON FUNCTION public.moderate_ad_report(uuid,text,text) TO authenticated;

-- 8) إجراءات إدارية للإعلان مع سجل تدقيق
CREATE OR REPLACE FUNCTION public.moderate_ad(
  p_ad_id uuid,
  p_status text
) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.has_permission('moderate_ads') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF p_status NOT IN ('active','hidden','deleted') THEN RAISE EXCEPTION 'حالة غير صالحة'; END IF;
  UPDATE public.ads SET status=p_status WHERE id=p_ad_id;
  IF NOT FOUND THEN RETURN false; END IF;
  PERFORM public.write_audit_log('ad_status_changed','ad',p_ad_id,jsonb_build_object('status',p_status));
  RETURN true;
END; $$;
GRANT EXECUTE ON FUNCTION public.moderate_ad(uuid,text) TO authenticated;

-- 9) سجل تغييرات المستخدمين عبر استبدال RPCs الإدارية الحالية
CREATE OR REPLACE FUNCTION public.admin_set_user_status(target_user_id uuid,new_status text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_old text; v_actor text;
BEGIN
  IF NOT public.has_permission('manage_users') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF new_status NOT IN ('active','suspended') THEN RAISE EXCEPTION 'حالة غير صالحة'; END IF;
  SELECT status, role INTO v_old, v_actor FROM public.profiles WHERE id=target_user_id FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  UPDATE public.profiles SET status=new_status,updated_at=now() WHERE id=target_user_id;
  PERFORM public.write_audit_log('user_status_changed','profile',target_user_id,jsonb_build_object('from',v_old,'to',new_status,'target_role',v_actor));
  RETURN true;
END; $$;
GRANT EXECUTE ON FUNCTION public.admin_set_user_status(uuid,text) TO authenticated;

